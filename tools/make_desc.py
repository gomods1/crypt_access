"""Builds the English picture descriptions for Crypt Access.

Sources (written from the game's art: cutscene frames, bestiary portraits, boss screens, sprites):
  tools/desc/desc_en.txt       key|text lines (characters, enemies, bosses, people, title screens, zones)
  tools/desc/cutscenes_en.md   per video: "- <seconds> <text>" lines under the video name

Writes:
  mod/CryptAccess/scripts/DescEN.lua           every description string (the other Desc*.lua are translations)
  mod/CryptAccess/scripts/CutsceneTimeline.lua when each cutscene description is spoken

python tools/make_desc.py
"""
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "tools", "desc")
OUT = os.path.join(ROOT, "mod", "CryptAccess", "scripts")


def esc(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def short_name(video):
    if video == "intro_silent":
        return "intro"
    if video == "intro_dlc_silent":
        return "introDlc"
    m = re.match(r"cutscene_(\w+?)_(\d+)$", video)
    if not m:
        raise SystemExit("unknown video name " + video)
    return m.group(1) + m.group(2)


entries = []
for line in open(os.path.join(SRC, "desc_en.txt"), encoding="utf-8"):
    line = line.rstrip("\n")
    if not line or line.startswith("#"):
        continue
    key, text = line.split("|", 1)
    entries.append((key, text))

timeline = {}
order = []
video = None
for line in open(os.path.join(SRC, "cutscenes_en.md"), encoding="utf-8"):
    line = line.rstrip("\n")
    m = re.match(r"^(intro\w*|cutscene_\w+)$", line)
    if m:
        video = m.group(1)
        timeline[video] = []
        order.append(video)
        continue
    m = re.match(r"^- (\d+(?:\.\d+)?) (.+)$", line)
    if m and video:
        n = len(timeline[video]) + 1
        key = "cs.%s.%d" % (short_name(video), n)
        timeline[video].append((float(m.group(1)), key))
        entries.append((key, m.group(2)))

keys = [k for k, _ in entries]
dupes = {k for k in keys if keys.count(k) > 1}
if dupes:
    raise SystemExit("duplicate keys: %s" % sorted(dupes))

with open(os.path.join(OUT, "DescEN.lua"), "w", encoding="utf-8", newline="\n") as f:
    f.write("-- English picture descriptions. Generated by tools/make_desc.py from tools/desc; edit those files.\n")
    f.write("return {\n")
    for key, text in entries:
        f.write('\t["%s"] = "%s",\n' % (key, esc(text)))
    f.write("}\n")

with open(os.path.join(OUT, "CutsceneTimeline.lua"), "w", encoding="utf-8", newline="\n") as f:
    f.write("-- When each cutscene description is spoken: video name -> { seconds, string key }.\n")
    f.write("-- Generated by tools/make_desc.py from tools/desc/cutscenes_en.md; edit that file.\n")
    f.write("return {\n")
    for video in order:
        f.write("\t%s = {\n" % video)
        for seconds, key in timeline[video]:
            f.write('\t\t{ %s, "%s" },\n' % (("%g" % seconds), key))
        f.write("\t},\n")
    f.write("}\n")

print(len(entries), "strings,", len(order), "videos")
